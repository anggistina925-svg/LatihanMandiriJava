public class Latihan1 {

    public static void main(String[] args) {

        System.out.println("Nomor Urut Barang");

        for (int i = 1; i <= 10; i++) {
            System.out.println("Barang ke-" + i);
        }

        System.out.println("\nNomor Urut Terbalik");

        for (int i = 10; i >= 1; i--) {
            System.out.println("Barang ke-" + i);
        }
    }
}
